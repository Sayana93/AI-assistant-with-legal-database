import streamlit as st
from gigachat import GigaChat
import PyPDF2
import os
from dotenv import load_dotenv

load_dotenv()

AUTH_DATA=os.getenv("GIGACHAT_AUTH_DATA")

st.set_page_config(page_title="ИИ-Помощник Служащего", page_icon="📝")
st.title("🤖 Ассистент муниципального служащего")
st.write("Генерация официальных ответов на базе GigaChat")

# Интерфейс в сайдбаре
with st.sidebar:
    st.header("Настройки")
    doc_type = st.selectbox("Тип документа", 
                            ["Заявление гражданина", "Ответ на требование прокуратуры", "Служебная записка", "Ходатайство"])
    #ДОБАВЛЕНИЕ: Загрузка файла
    uploaded_file = st.file_uploader("+", "pdf")
user_text = st.text_area("Введите краткую суть дела:", 
                         placeholder="Например: Прокурорская проверка по факту нарушения сроков...")
if st.button("Сгенерировать ответ"):
    if user_text:
        with st.spinner('ИИ-юрист составляет документ...'):
            try:
                # Используем правильную переменную AUTH_DATA
                with GigaChat(credentials=AUTH_DATA, model="GigaChat", verify_ssl_certs=False, timeout=60) as giga:
                    system_role = "Ты — ведущий эксперт по муниципальному праву и опытный юрист. Пишите строго в официально-деловом стиле. Ваши ответы должны быть глубоко проработанными, логически структурированными, содержать ссылки на нормы законодательства РФ (где применимо), а также учитывать все нюансы и возможные риски поставленной задачи."
                    
                    # Формируем запрос
                    prompt = f"""Строгие требования к стилю написания.
                                 Подготовьте проект официального документа в строгом официально-деловом стиле.
                                 Тип документа: {doc_type}.
                                 Суть дела и исходные данные: {user_text}.

                                 Требования к ответу:
                                 1. Соблюдайте логическую структуру и стандарты делопроизводства.
                                 2. Используйте профессиональную юридическую и муниципальную терминологию.
                                 3. Аргументируйте позицию четко, последовательно и без лишней «воды».
                                 4. Исключите использование личных местоимений ('мы', 'вы', 'я')."""
                    
                    # Отправляем как единый запрос (или используйте структуру ролей)
                    response = giga.chat(f"{system_role}\n\n{prompt}")
           
                    st.subheader("Результат:")
                    st.write(response.choices[0].message.content)
                    st.success("Готово!")
            except Exception as e:
                st.error(f"Ошибка подключения: {e}")
    else:
        st.warning("Пожалуйста, введите суть дела.")
# Добавляем обработку загруженного файла
if uploaded_file is not None:
    try:
        # 1. Читаем текст из PDF
        pdf_reader = PyPDF2.PdfReader(uploaded_file)
        pdf_text = ""
        for page in pdf_reader.pages:
                text = page.extract_text()
                pdf_text += text + "\n"    
        # Поле ввода сути дела
        user_text = st.text_area
        placeholeder="Например: Требование прокуратуры по ТКО"

        # . Кнопка для анализа
        if st.button("Проанализировать загруженный PDF"):
            if user_text:
               with st.spinner("ИИ изучает документ..."):

                # Формируем запрос к нейросети на основе текста из файла
                file_prompt = f"""На основе прикрепленного документа прокуратуры (требования) и сути дела подготовьте проект официального ответа органа местного самоуправления в строгом официально-деловом стиле.
                                  Тип документа: {doc_type}
                                  Суть дела и реальная позиция администрации: {user_text}
                                  Текст требования прокуратуры из прикрепленного файла: {pdf_text}
                                  Строгие требования к содержанию и стилю:
                                  1. КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО использовать любые личные и притяжательные местоимения («мы», «нас», «нами», «наш», «ваш», «я»). Используйте безличный стиль или конструкцию «Администрация муниципального образования».
                                  2. Ответьте по существу на каждый конкретный вопрос и пункт, поставленный прокуратурой в тексте требования (учет ТКО, весовой контроль, ФГИС УТКО, площадки, схемы и т.д.), опираясь на введенную суть дела.
                                  3. Соблюдайте структуру официального ответа: шапка, вводная часть (ссылка на требование), мотивированная позиция по каждому пункту, принятые меры.
                                  4. Обязательно включите формулировки: 'согласно постановлению и распоряжению', 'в установленный срок', 'доводы приняты'."""
                # Используем вашу функцию или прямой вызов GigaChat
                with GigaChat(credentials=AUTH_DATA, verify_ssl_certs=False) as giga:
                    res = giga.chat(file_prompt)
                    st.subheader("Проект ответа по файлу:")
                    st.write(res.choices[0].message.content)
                    st.success("Готово!")
    except Exception as e:
        st.error(f"Не удалось прочитать PDF: {e}")
    